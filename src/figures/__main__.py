"""Regenerate all main and supplementary manuscript figures.

`python -m src.figures`            Figures 2–4 and 6–10 and Supplementary Figures 1–11
`python -m src.figures fig2_PT`    one figure by its NAME

Figures are ported one at a time and validated by eye against the published
PDF, so this runner exists for reproducibility (and for `make figures`), not as
the normal way of working: during porting, run the module directly
(`python -m src.figures.fig2_pt`).

Each module must expose NAME and main(); the runner shares one loaded dataset so
that adding a figure does not re-read the HDF5 file. A module may declare
ADDITIONAL_OUTPUTS generated by the same step (Figure 7 also writes S6).
"""
import importlib
import sys
import traceback

REGISTRY = [
    "src.figures.fig2_pt",
    "src.figures.fig3_raman",
    "src.figures.fig4_comparison",
    "src.figures.fig6_ruptures",
    "src.figures.fig7_transitions",
    "src.figures.fig8_melt_areas",
    "src.figures.fig9_delta_tg",
    "src.figures.fig10_raman",
    "src.figures.supplementary_fig1",
    "src.figures.supplementary_fig2",
    "src.figures.supplementary_fig3",
    "src.figures.supplementary_fig4",
    "src.manuscript.supplementary_fig_5",
    "src.figures.supplementary_fig7",
    "src.figures.supplementary_fig8",
    "src.figures.supplementary_fig9",
    "src.figures.supplementary_fig10",
    "src.manuscript.Supplementary_Figure_11_viscosity",
]


def _modules(selected=None):
    """Resolve module paths, module names ("fig2_pt") or figure NAME ("fig2_PT")."""
    available = [importlib.import_module(m) for m in REGISTRY]
    if not selected:
        return available
    out = []
    for want in selected:
        match = [m for m in available
                 if want in (m.__name__, m.__name__.rsplit(".", 1)[-1], m.NAME,
                             *getattr(m, "ADDITIONAL_OUTPUTS", ()))]
        if not match:
            known = ", ".join(name for m in available
                              for name in (m.NAME, *getattr(m, "ADDITIONAL_OUTPUTS", ())))
            raise SystemExit(f"unknown figure {want!r}; available: {known}")
        # Selecting both Figure 7 and S6 must not run their shared fit twice.
        if match[0] not in out:
            out.append(match[0])
    return out


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    mods = _modules(argv or None)
    shared = None
    if len(mods) > 1:
        from ..figure_data import load_dataset
        shared = load_dataset()
    failures = []
    for mod in mods:
        try:
            mod.main(shared) if shared is not None else mod.main()
        except Exception as exc:                      # keep going, report at the end
            failures.append((mod.NAME, exc))
            traceback.print_exc()
    for name, exc in failures:
        print(f"[figures] FAILED {name}: {exc}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
